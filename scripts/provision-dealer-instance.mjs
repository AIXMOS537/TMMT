#!/usr/bin/env node
/**
 * Dealer instance provisioning factory — mom & pop dedicated deploy.
 * Dry-run by default. Does NOT auto-create Supabase/Vercel projects (manual gates).
 *
 * Usage:
 *   node scripts/provision-dealer-instance.mjs --dealer "Joe's Auto" --email owner@lot.com --dry-run
 *   node scripts/provision-dealer-instance.mjs --dealer "Joe's Auto" --email owner@lot.com --apply
 *
 * After GHL payment webhook tags kit-ordered-* — run with --apply to create admin + handoff pack.
 */
import { writeFileSync, mkdirSync, existsSync } from "fs";
import { join } from "path";
import { loadProjectEnv, root } from "./load-env.mjs";

function parseArgs() {
  const argv = process.argv.slice(2);
  const out = { dealer: "", email: "", sku: "ops", dryRun: true, output: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--dealer" && argv[i + 1]) out.dealer = argv[++i];
    else if (argv[i] === "--email" && argv[i + 1]) out.email = argv[++i].trim().toLowerCase();
    else if (argv[i] === "--sku" && argv[i + 1]) out.sku = argv[++i];
    else if (argv[i] === "--apply") out.dryRun = false;
    else if (argv[i] === "--dry-run") out.dryRun = true;
    else if (argv[i] === "--output" && argv[i + 1]) out.output = argv[++i];
    else if (argv[i] === "--help" || argv[i] === "-h") {
      console.log(`Usage: node scripts/provision-dealer-instance.mjs --dealer "Name" --email u@x.com [--sku ops|dealer] [--dry-run|--apply]`);
      process.exit(0);
    }
  }
  if (!out.dealer || !out.email) {
    console.error("Need --dealer and --email");
    process.exit(1);
  }
  return out;
}

const args = parseArgs();
const slug = args.dealer
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, "-")
  .replace(/^-|-$/g, "")
  .slice(0, 32);

const checklist = [
  { step: 1, task: "GHL payment received", tag: args.sku === "dealer" ? "kit-ordered-dealer-bundle" : "kit-ordered-ops", owner: "auto" },
  { step: 2, task: "Create Supabase project", ref: `dealer-${slug}`, owner: "ops" },
  { step: 3, task: "Run migrations on new project", cmd: "npm run db:migrate", owner: "ops" },
  { step: 4, task: "Create Vercel projects (tmmt-ops + command-center)", ref: `dealer-${slug}`, owner: "ops" },
  { step: 5, task: "Set env: SUPABASE_*, GHL_WEBHOOK_SECRET, COMMAND_CENTER bridge", owner: "ops" },
  { step: 6, task: "Deploy + smoke", cmd: "npm run smoke:prod", owner: "ops" },
  { step: 7, task: "Create admin user", cmd: `node scripts/provision-tenant-seat.mjs --email ${args.email} --vertical tmmt-rentals --stage admin --apply`, owner: "ops" },
  { step: 8, task: "GHL pipeline: Dealer Sales + tags dealer-prospect", owner: "ops" },
  { step: 9, task: "Hand off OPERATOR-START-HERE.md + login", owner: "success" },
  { step: 10, task: "14-day check-in scheduled", owner: "success" },
];

const handoffDir = join(root, "handoffs", slug);
const handoffPath = join(handoffDir, "OPERATOR-START-HERE.md");

const handoff = `# ${args.dealer} — Operator Start Here

**SKU:** ${args.sku === "dealer" ? "Dealer Bundle ($3,497 + $697/mo)" : "Ops Kit ($997 + $297/mo)"}  
**Admin email:** ${args.email}  
**Provisioned:** ${new Date().toISOString()}

## Your URLs (replace after deploy)

- Staff ops: \`https://tmmt-ops-${slug}.vercel.app/login\`
- Lead form: \`https://tmmt-ops-${slug}.vercel.app/forms/lead-intake\`
- Owner hub: \`https://tmmt-command-center-${slug}.vercel.app/login\` (Dealer Bundle only)

## Day 1

1. Log in · change password
2. Add your first vehicle / customer
3. Embed lead form on website or print QR
4. Book 14-day success call

## Support

See kit insert · GHL inbox · TMMT support line (set NEXT_PUBLIC_SUPPORT_PHONE in env)

---
*Generated by provision-dealer-instance.mjs — PROJECT X HAILMARY*
`;

console.log(`\n=== Dealer provision: ${args.dealer} (${slug}) ===`);
console.log(`Mode: ${args.dryRun ? "DRY-RUN" : "APPLY"}\n`);

for (const item of checklist) {
  console.log(`[${item.step}/10] ${item.task} (${item.owner})${item.cmd ? `\n       → ${item.cmd}` : ""}`);
}

if (args.dryRun) {
  console.log("\nDRY-RUN — no files written. Pass --apply to generate handoff pack.");
  process.exit(0);
}

mkdirSync(handoffDir, { recursive: true });
writeFileSync(handoffPath, handoff);
console.log(`\n✓ Handoff written: ${handoffPath}`);

if (args.output) {
  const outPath = args.output.startsWith("/") ? args.output : join(process.cwd(), args.output);
  writeFileSync(
    outPath,
    ["step,task,owner,status", ...checklist.map((c) => `${c.step},"${c.task}",${c.owner},pending`)].join("\n") + "\n"
  );
  console.log(`✓ Checklist CSV: ${outPath}`);
}

if (!loadProjectEnv()) {
  console.warn("WARN: .env not loaded — run provision-tenant-seat manually for step 7");
} else {
  console.log("\nNext: complete steps 2–6 in Supabase/Vercel, then run step 7 with --apply");
}
