#!/usr/bin/env node
/**
 * Writes public/aixmos/ghl-config.js from NEXT_PUBLIC_GHL_* env vars.
 * Run before build: npm run prebuild (or automatically via prebuild script).
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, "../public/aixmos/ghl-config.js");

const env = (key, fallback = "") => process.env[key]?.trim() || fallback;

const cfg = {
  checkout97: env("NEXT_PUBLIC_GHL_CHECKOUT_97", "YOUR_GHL_97_CHECKOUT_LINK"),
  checkoutLLC: env("NEXT_PUBLIC_GHL_CHECKOUT_LLC", "YOUR_GHL_LLC_CHECKOUT_LINK"),
  checkout3750: env("NEXT_PUBLIC_GHL_CHECKOUT_3750", "YOUR_GHL_3750_CHECKOUT_LINK"),
  operatorApply: env("NEXT_PUBLIC_GHL_OPERATOR_APPLY", "YOUR_GHL_OPERATOR_APPLICATION_LINK"),
  webhookUrl: env("NEXT_PUBLIC_GHL_WEBHOOK_URL", "YOUR_GHL_WEBHOOK_URL"),
  formEmbedUrl: env("NEXT_PUBLIC_GHL_FORM_EMBED", "YOUR_GHL_FORM_ID"),
  creditGuidance: env("NEXT_PUBLIC_GHL_CREDIT_GUIDANCE", "YOUR_GHL_CREDIT_GUIDANCE_LINK"),
};

mkdirSync(dirname(OUT), { recursive: true });

const js = `/**
 * AIXMOS — GoHighLevel links (generated by scripts/generate-ghl-config.mjs)
 * Set NEXT_PUBLIC_GHL_* in .env or Vercel, then npm run prebuild
 */
(function () {
  window.AIXMOS_GHL = ${JSON.stringify(cfg, null, 2)};

  function isLiveUrl(url) {
    if (!url || typeof url !== "string") return false;
    if (url.startsWith("YOUR_GHL_")) return false;
    return url.startsWith("http://") || url.startsWith("https://");
  }

  window.wireAixmosGhl = function wireAixmosGhl() {
    const cfg = window.AIXMOS_GHL;
    if (!cfg) return;

    document.querySelectorAll("[data-ghl-href]").forEach((el) => {
      const key = el.getAttribute("data-ghl-href");
      const url = cfg[key];
      if (isLiveUrl(url)) el.setAttribute("href", url);
    });

    document.querySelectorAll("[data-ghl-card]").forEach((card) => {
      const key = card.getAttribute("data-ghl-card");
      const url = cfg[key];
      if (!isLiveUrl(url)) return;
      const open = () => window.open(url, "_blank", "noopener,noreferrer");
      card.addEventListener("click", open);
      card.addEventListener("keydown", (e) => {
        if (e.key === "Enter" || e.key === " ") {
          e.preventDefault();
          open();
        }
      });
    });

    const embed = document.getElementById("ghl-form-embed");
    if (embed && isLiveUrl(cfg.formEmbedUrl)) embed.src = cfg.formEmbedUrl;
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", window.wireAixmosGhl);
  } else {
    window.wireAixmosGhl();
  }
})();
`;

writeFileSync(OUT, js, "utf8");
console.log("Wrote", OUT);
